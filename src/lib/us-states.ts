const CODES = new Set<string>(US_STATES.map((state) => state.code))

// La opción vacía obliga a elegir: un estado por defecto haría que un envío
// fuera de ese estado se cotizara y gravara mal.
export const US_STATE_OPTIONS = [
  { value: '', label: 'Select a state' },
  ...US_STATES.map((state) => ({ value: state.code, label: `${state.name} (${state.code})` })),
]

export function isUsStateCode(value: string): boolean {
  return CODES.has(value.trim().toUpperCase())
}

// Un perfil viejo puede tener "fl" o "Florida"; el select solo muestra códigos.
export function toUsStateCode(value: string | null | undefined): string {
  const raw = (value ?? '').trim()
  if (isUsStateCode(raw)) return raw.toUpperCase()
  const byName = US_STATES.find((state) => state.name.toLowerCase() === raw.toLowerCase())
  return byName?.code ?? ''
}
